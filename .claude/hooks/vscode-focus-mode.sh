#!/usr/bin/env bash
# SessionStart フック（任意の運用）:
# VS Code で開いたセッションでは「腰を据えた集中作業」を前提に会話を進めさせる。
#
# 「VS Code を開くのは座ってじっくり作業できるときだけ、スマホのアプリはスキマ時間」
# という使い分けをしている場合に効く仕組み。VS Code 環境のときだけ、その旨の文脈を
# モデルに注入し、通勤電車などのスキマ時間前提の話の展開（「まず概念だけ説明して、
# 座ったときに回せるコードは後で用意します」など）を避ける。
#
# 環境判定は CLAUDE_CODE_ENTRYPOINT で行う。
#   - VS Code ネイティブ拡張: "claude-vscode"
#   - ターミナル / web / スマホアプリ等: 別の値
# したがって VS Code 以外では何も注入せず、通常どおりの振る舞いになる。
# 値は実測に基づく（将来アプリ更新で変わる可能性はあるが、その場合はこの条件を直すだけでよい）。
#
# この運用が合わない場合の外し方は VSCODE_SETUP.md「VS Code で開いたセッションの扱い」を参照。
# Stop フック 2 本（check-uncommitted.sh / auto-merge-to-default.sh）の VS Code 判定と
# 3 点セットで動くので、外すときは揃えて外す。

set -euo pipefail

if [ "${CLAUDE_CODE_ENTRYPOINT:-}" != "claude-vscode" ]; then
  exit 0
fi

# additionalContext に渡す本文。JSON 文字列にそのまま埋め込むため、改行は \n で表現し、
# ASCII のダブルクォートは使わない（日本語引用符「」で代用）。動的な値は含めない。
printf '%s' '{"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":"このセッションは VS Code 上で開かれている。ユーザーは VS Code を「座ってじっくり作業できるとき」にのみ開くため、今回は腰を据えた集中学習セッションとして進めること。\n\n- スキマ時間（通勤電車など）前提の話の展開をしない。「まず概念だけ説明して、座ったときに回せるコードは後で用意します」のような、その場では手を動かせない前提の進め方をしない。\n- 説明・導出・具体例・演習は、その場で一緒に取り組む前提で提示してよい。コードもその場で実行して確かめる前提で用意・実行してよい。\n- CLAUDE.md の「宿題」の仕組みは引き続き有効だが、スキマ時間だからという理由での宿題化はしない。宿題にするのは、集中作業の時間内にも収まらないほど大きい計算・証明・演習に限り、まずはその場で一緒に進めることを既定とする。\n- VS Code で開いたセッションでは、Stop フックによる未 push チェックとデフォルトブランチへの自動マージが無効になっている。セッション終了時の commit・push は通常どおり行い、デフォルトブランチへのマージは自動では行われない旨をユーザーに一言添える。"}}'
